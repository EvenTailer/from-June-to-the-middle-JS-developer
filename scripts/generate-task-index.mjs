// Regenerates src/shared/content/tasks/taskIndex.ts and counts.ts from the
// task files. Both are derived data and must not be edited by hand.
import { readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { pathToFileURL } from 'node:url';

const ROOT = process.argv[2] ?? process.cwd();
const TASKS = join(ROOT, 'src/shared/content/tasks');

const TOPIC_DIR = join(TASKS, 'topics');
const CHAPTER_DIR = join(TASKS, 'chapters');

function collect(dir, filter) {
  const out = [];
  if (!exists(dir)) return out;
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) {
      // Barrels re-export leaf files and use extensionless imports that Node
      // cannot resolve, so subdirectories are skipped.
      continue;
    } else if (entry.endsWith('.ts') && filter(entry)) out.push(full);
  }
  return out;
}

function exists(dir) {
  try {
    statSync(dir);
    return true;
  } catch {
    return false;
  }
}

function isTask(value) {
  return (
    value &&
    typeof value === 'object' &&
    typeof value.id === 'string' &&
    value.brief &&
    typeof value.brief.en === 'string'
  );
}

async function tasksOf(file) {
  const mod = await import(pathToFileURL(file).href);
  const found = [];
  for (const value of Object.values(mod)) {
    if (Array.isArray(value)) {
      for (const item of value) if (isTask(item)) found.push({ task: item, fallbackModule: undefined });
    } else if (value && typeof value === 'object') {
      for (const [key, nested] of Object.entries(value)) {
        if (Array.isArray(nested)) {
          for (const item of nested) {
            if (isTask(item)) found.push({ task: item, fallbackModule: key });
          }
        }
      }
    }
  }
  return found;
}

const moduleById = {};
const topicById = {};

const topicFiles = collect(TOPIC_DIR, (name) => /^[^/]+\.ts$/.test(name) && name !== 'registry.ts');
const topicCounts = {};
const moduleTopicCounts = {};

for (const file of topicFiles) {
  const topic = relative(TOPIC_DIR, file).replace(/\.ts$/, '');
  const tasks = await tasksOf(file);
  topicCounts[topic] = tasks.length;
  for (const { task, fallbackModule } of tasks) {
    const moduleId = task.moduleId ?? fallbackModule;
    if (moduleId) {
      moduleTopicCounts[moduleId] = (moduleTopicCounts[moduleId] ?? 0) + 1;
      moduleById[task.id] = moduleId;
    }
    if (task.topic) topicById[task.id] = task.topic;
  }
}

// Module task files carry the module in the file name, not on the task.
const MODULE_FILES = {
  'base.ts': null,
  'htmlCss.ts': 'html-css',
  'git.ts': 'git',
  'cli.ts': 'cli',
  'oop.ts': 'oop',
  'http.ts': 'http',
  'jsCore.ts': 'js-core',
  'typescript.ts': 'typescript',
  'react.ts': 'react',
  'redux.ts': 'redux',
  'reactRouter.ts': 'react-router',
  'nextjs.ts': 'nextjs',
};

for (const [name, moduleId] of Object.entries(MODULE_FILES)) {
  const file = join(TASKS, name);
  if (!exists(file)) continue;
  for (const { task, fallbackModule } of await tasksOf(file)) {
    const owner = moduleId ?? task.moduleId ?? fallbackModule;
    if (owner) moduleById[task.id] = owner;
    if (task.topic) topicById[task.id] = task.topic;
  }
}

for (const file of collect(CHAPTER_DIR, (name) => name.endsWith('.ts'))) {
  for (const { task } of await tasksOf(file)) {
    if (task.moduleId) moduleById[task.id] = task.moduleId;
    if (task.topic) topicById[task.id] = task.topic;
  }
}

const header = `// Generated by scripts/generate-task-index.mjs. Do not edit by hand.
`;

writeFileSync(
  join(TASKS, 'taskIndex.ts'),
  `${header}export const taskModuleById: Record<string, string> = ${JSON.stringify(moduleById)};\n\n` +
    `export const taskTopicById: Record<string, string> = ${JSON.stringify(topicById)};\n`,
  'utf8'
);

const topicOrder = Object.keys(topicCounts).sort();
writeFileSync(
  join(TASKS, 'counts.ts'),
  `${header}import type { PracticeTopicId } from '../../../entities/module/model/types';\n\n` +
    `export const topicTaskCounts: Record<PracticeTopicId, number> = {\n` +
    topicOrder.map((topic) => `  '${topic}': ${topicCounts[topic]},`).join('\n') +
    `\n};\n\n` +
    `export const moduleTopicTaskCounts: Record<string, number> = {\n` +
    Object.keys(moduleTopicCounts)
      .sort()
      .map((moduleId) => `  '${moduleId}': ${moduleTopicCounts[moduleId]},`)
      .join('\n') +
    `\n};\n`,
  'utf8'
);

console.log(
  `taskIndex.ts: ${Object.keys(moduleById).length} ids, ${Object.keys(topicById).length} topics`
);
console.log(`counts.ts: ${topicOrder.length} topics, ${Object.keys(moduleTopicCounts).length} modules`);
